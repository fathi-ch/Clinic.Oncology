// Regenerates dx.accent.css: every DevExtreme light-theme rule that uses the theme's blue accent,
// moved to the app's accent (Radix Colors purple-9, #8e4ec6). Loaded after dx.light.css in angular.json.
// Run after upgrading DevExtreme:  node themes/recolor-dx-accent.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const source = new URL('../node_modules/devextreme/dist/css/dx.light.css', import.meta.url);
const target = new URL('./dx.accent.css', import.meta.url);

// DevExtreme's accent #337ab7 is hsl(207, 56%, 46%); purple-9 is hsl(272, 52%, 54%).
const FROM = { h: 207, s: 56, l: 46 };
const TO = { h: 272, s: 52, l: 54 };

const toHsl = (r, g, b) => {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return { h: 0, s: 0, l: l * 100 };
  const d = max - min, s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return { h: h * 60, s: s * 100, l: l * 100 };
};
const toRgb = ({ h, s, l }) => {
  s /= 100; l /= 100;
  const k = n => (n + h / 30) % 12, a = s * Math.min(l, 1 - l);
  const f = n => Math.round(255 * (l - a * Math.max(-1, Math.min(k(n) - 3, 9 - k(n), 1))));
  return [f(0), f(8), f(4)];
};
const isAccent = ({ h, s }) => h >= 200 && h <= 215 && s >= 35;
const shift = c => ({
  h: TO.h,
  s: Math.min(100, c.s * (TO.s / FROM.s)),
  l: Math.max(0, Math.min(100, c.l + (TO.l - FROM.l))),
});
const hex = rgb => '#' + rgb.map(v => v.toString(16).padStart(2, '0')).join('');

const recolor = text => text
  .replace(/#([0-9a-f]{6})\b/gi, (m, h) => {
    const c = toHsl(...[0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16)));
    return isAccent(c) ? hex(toRgb(shift(c))) : m;
  })
  .replace(/rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)/g, (m, r, g, b, a) => {
    const c = toHsl(+r, +g, +b);
    return isAccent(c) ? `rgba(${toRgb(shift(c)).join(', ')}, ${a})` : m;
  });

const css = readFileSync(source, 'utf8');
const rules = [];
for (const [, selector, body] of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
  const changed = recolor(body);
  if (changed === body) continue;
  // keep only the declarations whose color changed, so layout rules stay with the stock theme
  const decls = changed.split(';').filter((d, i) => d !== body.split(';')[i] && d.trim());
  rules.push(`${selector.trim()} {${decls.join(';')};}`);
}
writeFileSync(target, `/* Generated by recolor-dx-accent.mjs from DevExtreme dx.light.css. Do not edit by hand. */\n${rules.join('\n')}\n`);
console.log(`${rules.length} rules written to ${target.pathname}`);
